@file:Suppress("MatchingDeclarationName")

package com.letapay.app.feature.trade

import androidx.navigation.NavController
import androidx.navigation.NavGraphBuilder
import androidx.navigation.NavOptions
import androidx.navigation.compose.composable
import kotlinx.serialization.Serializable

@Serializable
data object TradeRoute

fun NavController.navigateToTrade(navOptions: NavOptions? = null) = navigate(TradeRoute, navOptions)

fun NavGraphBuilder.tradeDestination() {
    composable<TradeRoute> {
        TradeScreen()
    }
}
